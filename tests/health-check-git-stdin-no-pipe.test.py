#!/usr/bin/env python3
"""Git stdin in health-check must come from a file, never from `subprocess.run(input=)`.

`_carrier_target_verdict` feeds `git check-ignore -v -z --stdin` the whole carrier
tree (~11k paths on a real workspace); git flushes one record per path. When
macOS's system-wide pipe-buffer pool is spent, a new pipe holds 512 bytes yet
poll() still reports it writable, so `communicate()` sleeps in a blocking
os.write() on git's stdin while git sleeps writing its stdout. `timeout=` is
only checked around select(), so it never fires: the probe hung 8-15 min and
took every proactive-loop health step with it. `_index_growth_note` feeds
`git cat-file --batch` at most 12 short specs, which cannot deadlock; it is
held to the same shape defensively.

The spent-pool reproduction is tests/health-check-git-stdin-pipe-pool.test.py
(macOS, opt-in). This suite pins the shape on every host: (1) an AST walk
asserting neither git call site passes `input=`, and (2) >64 KiB of real input
through each call site, with git's answer checked.

Run: python3 tests/health-check-git-stdin-no-pipe.test.py
"""

from _helpers.hermetic_env import isolate_os_environ, isolated_child_env

# Before anything reads the environment: no outer credential selector survives.
isolate_os_environ()

import ast
import importlib.util
import os
import subprocess
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src" / "health-check.py"
PIPE_BUF = 64 * 1024

fails = []


def check(name, got, want):
    ok = got == want
    print(f"  {'ok  ' if ok else 'FAIL'} {name}")
    if not ok:
        print(f"       got {got!r}, want {want!r}")
        fails.append(name)


# ---- 1. the call shape ------------------------------------------------------

def _git_subcommand(call: ast.Call) -> "str | None":
    """The git subcommand of a `subprocess.run(git_argv(...), ...)` call, or None."""
    f = call.func
    if not (isinstance(f, ast.Attribute) and f.attr == "run"
            and isinstance(f.value, ast.Name) and f.value.id == "subprocess"):
        return None
    if not call.args:
        return None
    argv = call.args[0]
    if not (isinstance(argv, ast.Call) and isinstance(argv.func, ast.Name)
            and argv.func.id == "git_argv"):
        return None
    words = [a.value for a in argv.args if isinstance(a, ast.Constant) and isinstance(a.value, str)]
    for w in words:
        if w in ("check-ignore", "cat-file"):
            return w
    return None


tree = ast.parse(SRC.read_text(), filename=str(SRC))
sites = {}
for node in ast.walk(tree):
    if isinstance(node, ast.Call):
        sub = _git_subcommand(node)
        if sub:
            sites.setdefault(sub, []).append({kw.arg for kw in node.keywords})

# Both sites must be FOUND: a walk that matches nothing passes vacuously.
check("the check-ignore call site is located", len(sites.get("check-ignore", [])), 1)
check("the cat-file call site is located", len(sites.get("cat-file", [])), 1)
for sub, kwsets in sorted(sites.items()):
    for kws in kwsets:
        check(f"{sub}: no `input=` (a pipe write that can block past the timeout)",
              "input" in kws, False)
        check(f"{sub}: stdin is supplied explicitly", "stdin" in kws, True)
        check(f"{sub}: output is still captured", "capture_output" in kws, True)
        check(f"{sub}: timeout is still set", "timeout" in kws, True)


# ---- 2. >64 KiB through each site, for real ---------------------------------

def load():
    spec = importlib.util.spec_from_file_location("hc_stdin", SRC)
    m = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(m)
    except SystemExit:
        pass
    return m


m = load()

# Ambient gc/maintenance/hooks must not touch the temp repos (#3542 shape).
GENV = isolated_child_env(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_SYSTEM=os.devnull,
            GIT_CONFIG_NOSYSTEM="1")
GIT = ["git", "-c", "gc.auto=0", "-c", "maintenance.auto=false", "-c", "core.fsmonitor=false"]


def carrier_workspace(tmp: Path, nfiles: int, extra_exclude: str = "") -> Path:
    """A workspace whose `notes/` carrier entry has `nfiles` files beneath it."""
    ws = tmp / "workspace"
    ws.mkdir()
    subprocess.run(GIT + ["init", "-q", str(ws)], env=GENV, check=True)
    notes = ws / "notes"
    for i in range(nfiles):
        d = notes / f"section-{i % 50:02d}"
        d.mkdir(parents=True, exist_ok=True)
        (d / f"a-reasonably-long-note-name-{i:05d}.md").write_text("x\n")
    info = ws / ".git" / "info"
    info.mkdir(parents=True, exist_ok=True)
    (info / "exclude").write_text(
        "# Generated by sync-workspace.sh — do not edit by hand.\n*\n"
        "!notes/\n!notes/**\n" + extra_exclude
    )
    return ws


with tempfile.TemporaryDirectory() as td:
    ws = carrier_workspace(Path(td), nfiles=2000)
    targets = m._carrier_probe_files(ws / "notes")
    payload = len("\0".join(str(t.relative_to(ws)) for t in targets).encode())
    check("check-ignore input exceeds the pipe buffer", payload > PIPE_BUF, True)
    t0 = time.monotonic()
    verdict = m._carrier_target_verdict(ws, ws / "notes")
    took = time.monotonic() - t0
    check("a fully carried 2000-file tree reads carried", verdict, "carried")
    check("...and returns well inside the timeout", took < 30, True)

with tempfile.TemporaryDirectory() as td:
    # The one condemning rule sits LAST in a >64 KiB batch, so a truncated or
    # partially consumed stdin would read as carried.
    ws = carrier_workspace(Path(td), nfiles=2000, extra_exclude="a-reasonably-long-note-name-01999.md\n")
    check("one operator-ignored file at the end of the batch reads dropped",
          m._carrier_target_verdict(ws, ws / "notes"), "dropped")


def index_repo(tmp: Path, revisions: int, size: int) -> Path:
    d = tmp / "memory"
    d.mkdir()
    idx = d / "MEMORY.md"
    subprocess.run(GIT + ["init", "-q", str(d)], env=GENV, check=True)
    subprocess.run(GIT + ["-C", str(d), "config", "user.email", "t@t"], env=GENV, check=True)
    subprocess.run(GIT + ["-C", str(d), "config", "user.name", "t"], env=GENV, check=True)
    now = int(time.time())
    for i in range(revisions):
        idx.write_text("- [x](x.md) — " + "y" * (size - (revisions - 1 - i) * 1000) + "\n")
        env = dict(GENV, GIT_AUTHOR_DATE=str(now - (revisions - i) * 3600),
                   GIT_COMMITTER_DATE=str(now - (revisions - i) * 3600))
        subprocess.run(GIT + ["-C", str(d), "add", "MEMORY.md"], env=GENV, check=True)
        subprocess.run(GIT + ["-C", str(d), "commit", "-q", "-m", f"c{i}"], env=env, check=True)
    return idx


with tempfile.TemporaryDirectory() as td:
    # cat-file's stdin is short (one spec per revision) but its stdout is the
    # blobs themselves; 12 revisions x 20 KB puts git's side well past the pipe.
    idx = index_repo(Path(td), revisions=12, size=20_000)
    eff = len(m._index_effective_text(idx.read_text()).encode())
    note = m._index_growth_note(idx, eff)
    check("cat-file over >64 KiB of blob output yields a real trend", "over the last" in note, True)
    check("...and never the unavailable marker", "growth trend unavailable" in note, False)


if fails:
    print(f"\n{len(fails)} FAILED: {fails}")
    raise SystemExit(1)
print("\nall ok")
